import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";
import {
  role,
  stage,
  workerType,
  provider,
  subject,
  box,
  markType,
  anchor,
  arrow,
  span,
  neutral,
  provenance,
  renderMode,
  trackMode,
  source,
  focus,
  note,
  stillRef,
  segmentRef,
  stageStatus,
  jobKind,
  jobStatus,
} from "./validators";
import { modelOutput } from "./modelOutputs";
import { errorCode } from "./errorCodes";
export default defineSchema({
  coaches: defineTable({
    clerkUserId: v.string(),
    displayName: v.string(),
    createdAt: v.number(),
  }).index("by_clerkUserId", ["clerkUserId"]),
  students: defineTable({
    coachId: v.id("coaches"),
    label: v.string(),
    contactMasked: v.optional(v.string()),
    createdAt: v.number(),
  }).index("by_coachId", ["coachId"]),
  sessions: defineTable({
    coachId: v.id("coaches"),
    studentId: v.id("students"),
    subjectRole: role,
    subject: v.optional(subject),
    subjectStatus: v.union(
      v.literal("needed"),
      v.literal("set"),
      v.literal("anchored"),
      v.literal("anchor_failed"),
    ),
    subjectAnchor: v.optional(
      v.object({ box: box, frameMs: v.number(), referenceCropKey: v.string() }),
    ),
    captureMode: v.union(
      v.literal("camera"),
      v.literal("camera_roll"),
      v.literal("in_page"),
    ),
    renderMode: renderMode,
    consentConfirmedAt: v.optional(v.number()),
    consentConfirmedBy: v.optional(v.string()),
    isDemoFallback: v.boolean(),
    status: v.union(
      v.literal("draft"),
      v.literal("uploading"),
      v.literal("processing"),
      v.literal("needs_you"),
      v.literal("review_ready"),
      v.literal("shared"),
      v.literal("failed"),
    ),
    latestJobId: v.optional(v.id("jobs")),
    durationMs: v.optional(v.number()),
    createdAt: v.number(),
  }).index("by_coachId_createdAt", ["coachId", "createdAt"]),
  uploads: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    storageKey: v.string(),
    driver: v.union(v.literal("r2"), v.literal("local")),
    multipartUploadId: v.optional(v.string()),
    mimeType: v.string(),
    bytesTotal: v.number(),
    bytesConfirmed: v.number(),
    partSize: v.number(),
    partsConfirmed: v.array(v.number()),
    sha256: v.string(),
    status: v.union(
      v.literal("in_progress"),
      v.literal("paused"),
      v.literal("complete"),
      v.literal("failed"),
      v.literal("aborted"),
    ),
    attempts: v.number(),
    createdAt: v.number(),
    completedAt: v.optional(v.number()),
  }).index("by_sessionId", ["sessionId"]),
  pipeline_config: defineTable({
    version: v.number(),
    active: v.boolean(),
    stages: v.array(
      v.object({
        stage: stage,
        coachLabel: v.string(),
        workerId: v.string(),
        workerType: workerType,
        provider: provider,
        model: v.union(v.string(), v.null()),
        fanOut: v.union(v.literal("none"), v.literal("per_remark")),
        timeoutMs: v.number(),
        retry: v.number(),
        fallbackWorker: v.union(v.string(), v.null()),
        candidates: v.array(v.string()),
        enabled: v.boolean(),
        critic: v.union(
          v.object({
            workerId: v.string(),
            provider: provider,
            model: v.string(),
            enabled: v.boolean(),
          }),
          v.null(),
        ),
      }),
    ),
    coachStages: v.array(v.string()),
    limits: v.object({
      jobSamFrameCap: v.number(),
      jobSparkTokenCap: v.number(),
      fanoutConcurrency: v.number(),
      dailySpendLimitUsd: v.number(),
      sandboxTimeoutCapS: v.number(),
      sandboxIdleTimeoutS: v.number(),
      jobMaxAttempts: v.number(),
      maxVideoMinutes: v.number(),
      jobLeaseS: v.number(),
    }),
    params: v.object({
      personConcept: v.string(),
      minPersonConfidence: v.number(),
      maxMomentMs: v.number(),
      momentLookbackMs: v.number(),
      keyframeFps: v.number(),
      trackPadMs: v.number(),
      downsampleFps: v.union(v.number(), v.null()),
      minMarkCoverage: v.number(),
      stillsThreshold: v.number(),
      allowedMarkTypes: v.array(markType),
      maxMarksPerRemark: v.number(),
      labelMaxChars: v.number(),
      renderModeDefault: renderMode,
      otherPersonRemarksInShare: v.boolean(),
      anchorReuseMs: v.number(),
      reassocIouMin: v.number(),
      swapIouMin: v.number(),
      swapJumpFrac: v.number(),
      maxSubjectCandidates: v.number(),
      subjectModel: v.string(),
      segmentationModel: v.string(),
    }),
    createdAt: v.number(),
    note: v.string(),
  })
    .index("by_version", ["version"])
    .index("by_active", ["active"]),
  jobs: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    kind: jobKind,
    remarkId: v.optional(v.string()),
    stage: v.optional(stage),
    configVersion: v.number(),
    status: jobStatus,
    coachStage: v.string(),
    progress: v.optional(v.number()),
    progressLabel: v.optional(v.string()),
    errorCode: v.optional(errorCode),
    attempt: v.number(),
    maxAttempts: v.number(),
    leaseOwner: v.optional(v.string()),
    leaseUntil: v.optional(v.number()),
    heartbeatAt: v.optional(v.number()),
    sandboxId: v.optional(v.string()),
    sandboxName: v.optional(v.string()),
    lastStageDone: v.optional(stage),
    samFrames: v.number(),
    inputTokens: v.number(),
    outputTokens: v.number(),
    costUsd: v.number(),
    createdAt: v.number(),
    startedAt: v.optional(v.number()),
    endedAt: v.optional(v.number()),
  })
    .index("by_status_createdAt", ["status", "createdAt"])
    .index("by_sessionId", ["sessionId"]),
  sandboxes: defineTable({
    coachId: v.id("coaches"),
    jobId: v.id("jobs"),
    sandboxId: v.string(),
    sandboxName: v.string(),
    driver: v.union(v.literal("modal"), v.literal("local")),
    createdAt: v.number(),
    terminatedAt: v.optional(v.number()),
    terminatedBy: v.optional(
      v.union(
        v.literal("orchestrator"),
        v.literal("sweeper"),
        v.literal("timeout"),
        v.literal("self"),
      ),
    ),
    exitCode: v.optional(v.number()),
  })
    .index("by_jobId", ["jobId"])
    .index("by_terminatedAt", ["terminatedAt"]),
  stageRuns: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    jobId: v.id("jobs"),
    stage: stage,
    remarkId: v.optional(v.string()),
    workerId: v.string(),
    workerType: workerType,
    provider: provider,
    modelVersion: v.optional(v.string()),
    promptHash: v.optional(v.string()),
    candidate: v.optional(v.string()),
    attempt: v.number(),
    idempotencyKey: v.string(),
    status: stageStatus,
    errorCode: v.optional(errorCode),
    errorDetail: v.optional(v.string()),
    inputHash: v.string(),
    persistedOutputHash: v.optional(v.string()),
    persistedTrackBinding: v.optional(
      v.object({ trackId: v.string(), fileRef: v.string() }),
    ),
    persistedAnnotationIds: v.optional(
      v.array(
        v.object({ markId: v.string(), annotationId: v.id("annotations") }),
      ),
    ),
    outputRef: v.optional(v.string()),
    startedAt: v.optional(v.number()),
    endedAt: v.optional(v.number()),
    latencyMs: v.optional(v.number()),
    samFrames: v.optional(v.number()),
    inputTokens: v.optional(v.number()),
    outputTokens: v.optional(v.number()),
    costUsd: v.optional(v.number()),
  })
    .index("by_jobId_stage", ["jobId", "stage"])
    .index("by_jobId_remarkId", ["jobId", "remarkId"])
    .index("by_idempotencyKey", ["idempotencyKey"]),
  transcriptTurns: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    turnId: v.string(),
    startMs: v.number(),
    endMs: v.number(),
    speaker: v.string(),
    text: v.string(),
    correctedText: v.optional(v.string()),
    correctedAt: v.optional(v.number()),
  }).index("by_sessionId_turnId", ["sessionId", "turnId"]),
  remarks: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    remarkId: v.string(),
    turnIds: v.array(v.string()),
    source: v.union(v.literal("voice"), v.literal("typed")),
    aboutSubject: v.union(
      v.literal("yes"),
      v.literal("no"),
      v.literal("unclear"),
      v.literal("general"),
    ),
    kind: v.union(
      v.literal("feedback"),
      v.literal("instruction"),
      v.literal("praise"),
      v.literal("other"),
    ),
    atMs: v.number(),
    mode: v.union(
      v.literal("tracked"),
      v.literal("still_frame"),
      v.literal("note_only"),
    ),
    momentStartMs: v.optional(v.number()),
    momentEndMs: v.optional(v.number()),
    keyframeMs: v.optional(v.number()),
    momentWhy: v.optional(v.string()),
    status: v.union(
      v.literal("pending"),
      v.literal("ok"),
      v.literal("player_missing"),
      v.literal("needs_coach"),
    ),
    includeInShare: v.boolean(),
  }).index("by_sessionId", ["sessionId"]),
  annotations: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    remarkId: v.string(),
    markId: v.string(),
    markType: markType,
    anchor: anchor,
    arrowFrom: v.optional(arrow),
    role: role,
    startMs: v.number(),
    endMs: v.number(),
    labelSpan: v.optional(span),
    labelText: v.string(),
    neutralLabel: v.optional(neutral),
    trackId: v.optional(v.string()),
    why: v.string(),
    status: v.union(
      v.literal("needs_you"),
      v.literal("approved"),
      v.literal("deleted"),
      v.literal("player_missing"),
    ),
    placedBy: v.union(v.literal("ai"), v.literal("coach")),
    aiPlacement: v.optional(
      v.object({
        markType: markType,
        anchor: anchor,
        arrowFrom: v.optional(arrow),
        startMs: v.number(),
        endMs: v.number(),
        labelSpan: v.optional(span),
        labelText: v.string(),
        neutralLabel: v.optional(neutral),
      }),
    ),
    checkVerdict: v.optional(
      v.object({
        pass: v.boolean(),
        reason: v.union(
          v.literal("ok"),
          v.literal("no_player"),
          v.literal("subject_swap"),
          v.literal("low_coverage"),
          v.literal("outside_moment"),
          v.literal("label_mismatch"),
          v.literal("label_too_long"),
        ),
      }),
    ),
    provenance: provenance,
    approvedAt: v.optional(v.number()),
    updatedAt: v.number(),
  })
    .index("by_sessionId_status", ["sessionId", "status"])
    .index("by_remarkId", ["remarkId"]),
  tracks: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    remarkId: v.string(),
    trackId: v.string(),
    role: role,
    mode: trackMode,
    fileRef: v.string(),
    maskRef: v.optional(v.string()),
    coverage: v.number(),
    cacheKey: v.string(),
  })
    .index("by_sessionId", ["sessionId"])
    .index("by_cacheKey", ["cacheKey"])
    .index("by_trackId", ["trackId"]),
  agentTraces: defineTable({
    coachId: v.id("coaches"),
    stageRunId: v.id("stageRuns"),
    jobId: v.id("jobs"),
    remarkId: v.optional(v.string()),
    model: v.string(),
    promptHash: v.string(),
    framesViewed: v.optional(v.array(v.number())),
    parsedOutput: modelOutput,
    why: v.optional(v.string()),
    latencyMs: v.number(),
    inputTokens: v.number(),
    outputTokens: v.number(),
  }).index("by_stageRunId", ["stageRunId"]),
  renders: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    jobId: v.id("jobs"),
    kind: v.union(v.literal("preview"), v.literal("final")),
    mode: renderMode,
    fileRef: v.optional(v.string()),
    stillRefs: v.array(stillRef),
    segmentRefs: v.array(segmentRef),
    status: v.union(v.literal("ready"), v.literal("failed")),
    createdAt: v.number(),
  }).index("by_sessionId_kind", ["sessionId", "kind"]),
  lessons: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    notes: v.array(note),
    focusPoints: v.array(focus),
    practice: v.array(focus),
    nextSessionFocus: v.optional(
      v.object({
        title: v.string(),
        why: v.string(),
        remarkIds: v.array(v.string()),
        source: source,
        approved: v.boolean(),
      }),
    ),
    snapshotId: v.optional(v.id("lessonSnapshots")),
  }).index("by_sessionId", ["sessionId"]),
  lessonSnapshots: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    createdAt: v.number(),
    payload: v.object({
      media: v.object({
        proxyKey: v.string(),
        audioM4aKey: v.optional(v.string()),
      }),
      turns: v.array(
        v.object({
          turnId: v.string(),
          startMs: v.number(),
          endMs: v.number(),
          text: v.string(),
        }),
      ),
      remarks: v.array(
        v.object({
          remarkId: v.string(),
          turnIds: v.array(v.string()),
          coachWords: v.string(),
          atMs: v.number(),
          source: v.union(v.literal("voice"), v.literal("typed")),
        }),
      ),
      annotations: v.array(
        v.object({
          annotationId: v.string(),
          remarkId: v.string(),
          markId: v.string(),
          markType: markType,
          anchor: anchor,
          arrowFrom: v.optional(arrow),
          role: role,
          startMs: v.number(),
          endMs: v.number(),
          labelText: v.string(),
          placedBy: v.union(v.literal("ai"), v.literal("coach")),
          trackId: v.optional(v.string()),
          why: v.string(),
        }),
      ),
      focusPoints: v.array(focus),
      practice: v.array(focus),
      notes: v.array(note),
      renderRefs: v.array(
        v.object({
          kind: v.union(v.literal("preview"), v.literal("final")),
          fileRef: v.optional(v.string()),
          stillRefs: v.array(stillRef),
          segmentRefs: v.array(segmentRef),
        }),
      ),
      trackRefs: v.array(
        v.object({ trackId: v.string(), fileRef: v.string() }),
      ),
    }),
    renderMode: renderMode,
  }).index("by_sessionId", ["sessionId"]),
  shareLinks: defineTable({
    sessionId: v.id("sessions"),
    coachId: v.id("coaches"),
    snapshotId: v.id("lessonSnapshots"),
    tokenHash: v.string(),
    codeHash: v.string(),
    createdAt: v.number(),
    expiresAt: v.number(),
    revokedAt: v.optional(v.number()),
    openedAt: v.optional(v.number()),
    failedAttempts: v.number(),
    lockedUntil: v.optional(v.number()),
  })
    .index("by_tokenHash", ["tokenHash"])
    .index("by_sessionId", ["sessionId"]),
  costLedger: defineTable({
    coachId: v.id("coaches"),
    day: v.string(),
    jobId: v.id("jobs"),
    stage: stage,
    provider: provider,
    units: v.union(
      v.literal("samFrames"),
      v.literal("tokens"),
      v.literal("audioSeconds"),
      v.literal("sandboxSeconds"),
    ),
    quantity: v.number(),
    usd: v.number(),
  }).index("by_day", ["day"]),
});
